// Writes db/seed.sql from the content files, so the database starts with exactly
// what the site shows today. Run with `npm run seed:sql` after changing content/ by hand.
//
// The seed only inserts rows that do not exist yet (on conflict do nothing), so running it
// again never overwrites changes made in the admin console.
// Site texts are not copied: they stay in content/<lang>.json, and the admin stores only
// the texts it changes (table text_overrides).
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { business } from "../content/business.ts";
import { categoryImages } from "../content/photos.ts";
import catalogues from "../content/catalogues.json" with { type: "json" };
import offers from "../content/offers.json" with { type: "json" };

const q = (v) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  if (Array.isArray(v)) return `array[${v.map(q).join(", ")}]::text[]`;
  return `'${String(v).replaceAll("'", "''")}'`;
};
const row = (values) => `(${values.map(q).join(", ")})`;

const b = business;
const lines = [
  "-- Generated by scripts/make-seed.mjs from content/. Do not edit by hand.",
  "-- Inserts only missing rows, so it never overwrites edits made in the admin console.",
  "",
  "insert into public.business (id, phone_display, phone_international, phone_tel, phone_whatsapp, email, gstin,",
  "  street, locality, region, postal_code, country, latitude, longitude, directions_url, maps_embed_url,",
  "  opening_days, opens, closes, years_experience, instagram_url, facebook_url, youtube_url)",
  "values " +
    row([
      1, b.phone.display, b.phone.international, b.phone.tel, b.phone.whatsapp, b.email, b.gstin,
      b.address.street, b.address.locality, b.address.region, b.address.postalCode, b.address.country,
      b.geo?.latitude ?? null, b.geo?.longitude ?? null, b.directionsUrl, b.mapsEmbedUrl,
      b.openingHours.days, b.openingHours.opens, b.openingHours.closes, b.yearsExperience,
      b.socials.instagram, b.socials.facebook, b.socials.youtube,
    ]),
  "on conflict (id) do nothing;",
  "",
  "insert into public.offers (id, enabled, start_date, end_date, bill_tier1_min, bill_tier1_percent, bill_tier2_min,",
  "  bill_tier2_percent, gift_pack_value, refer_friend_saves, refer_you_earn, refer_min_first_bill, gold_visits,",
  "  gold_yearly_spend, gold_extra_percent)",
  "values " +
    row([
      1, offers.enabled, offers.startDate, offers.endDate, offers.billTier1Min, offers.billTier1Percent,
      offers.billTier2Min, offers.billTier2Percent, offers.giftPackValue, offers.referFriendSaves,
      offers.referYouEarn, offers.referMinFirstBill, offers.goldVisits, offers.goldYearlySpend, offers.goldExtraPercent,
    ]),
  "on conflict (id) do nothing;",
  "",
];

// Brands: placement and order from business.ts, catalogue details from catalogues.json.
const placements = [
  ["key", [b.keyPartner]],
  ["row2", b.authorisedBrands.row2],
  ["row3", b.authorisedBrands.row3],
  ["also", b.alsoDealIn],
];
const brandRows = [];
let position = 0;
for (const [placement, list] of placements) {
  for (const brand of list) {
    const cat = catalogues.brands.find((c) => c.slug === brand.slug);
    if (!cat) throw new Error(`No catalogues.json entry for brand ${brand.slug}`);
    brandRows.push(
      row([
        brand.slug, brand.name, brand.logo, brand.width ?? null, brand.height ?? null, placement, (position += 10),
        cat.pdf, cat.updated, cat.categories.en, cat.categories.hi, cat.categories.mr,
      ]),
    );
  }
}
lines.push(
  "insert into public.brands (slug, name, logo_path, logo_width, logo_height, placement, position,",
  "  catalogue_pdf, catalogue_updated, supplies_en, supplies_hi, supplies_mr)",
  "values",
  brandRows.map((r) => "  " + r).join(",\n"),
  "on conflict (slug) do nothing;",
  "",
);

// Categories, in card order. The slug is the illustration's file name.
const categoryRows = categoryImages.map((img, i) => {
  const slug = img.src.match(/([a-z0-9-]+)\.(svg|jpe?g|png|webp)$/)?.[1];
  if (!slug) throw new Error(`Cannot tell the category slug from ${img.src}`);
  return row([slug, (i + 1) * 10, img.src, img.width, img.height]);
});
lines.push(
  "insert into public.categories (slug, position, image_src, image_width, image_height)",
  "values",
  categoryRows.map((r) => "  " + r).join(",\n"),
  "on conflict (slug) do nothing;",
  "",
  "insert into public.settings (key, value)",
  "values ('retention_months', '12'::jsonb)",
  "on conflict (key) do nothing;",
  "",
  "-- The first owner is added by hand once the database exists (see DEPLOY.md):",
  "-- insert into public.admin_users (email, role, display_name) values ('owner@example.com', 'owner', 'Name');",
  "",
);

const out = fileURLToPath(new URL("../db/seed.sql", import.meta.url));
await writeFile(out, lines.join("\n"));
console.log(`make-seed: wrote ${out}`);
